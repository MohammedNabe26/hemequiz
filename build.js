// node build.js  -> writes questions.js (shared by the app and by push/send.js)
const fs = require('fs'), vm = require('vm'), path = require('path');
const ctx = {}; ctx.window = ctx; vm.createContext(ctx);
['q01_05', 'q06_10', 'q11_15', 'q16_19', 'q20_24', 'q25_30', 'q31_35'].forEach(f => vm.runInContext(fs.readFileSync(path.join(__dirname, 'data', f + '.js'), 'utf8'), ctx));
const rows = ctx.QB;
const out = '/* generated by build.js - edit data/*.js instead */\n(function(g){var QB=' + JSON.stringify(rows) + ';g.QB=QB;if(typeof module!=="undefined")module.exports=QB;})(typeof window!=="undefined"?window:globalThis);\n';
fs.writeFileSync(path.join(__dirname, 'questions.js'), out);
console.log('questions.js:', rows.length, 'questions');
